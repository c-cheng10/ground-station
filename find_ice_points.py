"""List grid points on ice sheets, where GLDAS 2.0 Noah has no glacier physics.

On permanent ice the model never melts its snowpack, so snow depth grows without limit (about 4 m a
year on Greenland) and its soil moisture and evaporation there mean nothing. A point counts as ice
when its snow depth never drops below 0.5 m or its yearly mean grows more than 2 m over the record.

    python find_ice_points.py     # reads giovanni-cache/, writes ice-points.js
"""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent


def snow_depths(path):
    text = path.read_text(encoding="utf-8")
    if "Timestamp" not in text:
        return []
    values = []
    for line in text.split("Timestamp", 1)[1].splitlines()[1:]:
        try:
            values.append(float(line.split(",")[1]))
        except (IndexError, ValueError):
            pass
    return values


def main():
    ice = []
    for folder in sorted((ROOT / "giovanni-cache").glob("*_*")):
        depths = snow_depths(folder / "2_0_SnowDepth_inst.csv") if (folder / "2_0_SnowDepth_inst.csv").exists() else []
        if len(depths) < 24:
            continue
        growth = sum(depths[-12:]) / 12 - sum(depths[:12]) / 12
        if min(depths) > 0.5 or growth > 2:
            ice.append(folder.name.replace("_", ","))
    (ROOT / "ice-points.js").write_text(
        "// Generated by find_ice_points.py: GLDAS points on ice sheets (runaway snow accumulation).\n"
        f"window.ICE_POINTS = {json.dumps(ice)};\n", encoding="utf-8")
    print(f"Wrote ice-points.js with {len(ice)} points.")


if __name__ == "__main__":
    main()
